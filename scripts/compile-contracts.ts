import fs from 'fs';
import path from 'path';
import solc from 'solc';

const CONTRACT_FILENAME = 'TrustGraphRegistry.sol';
const CONTRACT_NAME = 'TrustGraphRegistry';

export function compileTrustGraphRegistry() {
  const contractPath = path.join(process.cwd(), 'contracts', CONTRACT_FILENAME);
  if (!fs.existsSync(contractPath)) {
    throw new Error(`Contract source not found at ${contractPath}`);
  }

  const source = fs.readFileSync(contractPath, 'utf8');

  const input = {
    language: 'Solidity',
    sources: {
      [CONTRACT_FILENAME]: {
        content: source,
      },
    },
    settings: {
      evmVersion: 'paris',
      optimizer: {
        enabled: true,
        runs: 200,
      },
      outputSelection: {
        '*': {
          '*': ['abi', 'evm.bytecode.object', 'evm.deployedBytecode.object'],
        },
      },
    },
  };

  const rawOutput = solc.compile(JSON.stringify(input));
  const output = JSON.parse(rawOutput);

  if (output.errors && output.errors.length > 0) {
    const fatalErrors = output.errors.filter((e: any) => e.severity === 'error');
    for (const msg of output.errors) {
      if (msg.severity === 'error') {
        console.error(`[Solc Error] ${msg.formattedMessage}`);
      } else {
        console.warn(`[Solc Warning] ${msg.formattedMessage}`);
      }
    }
    if (fatalErrors.length > 0) {
      throw new Error(`Solidity compilation failed with ${fatalErrors.length} error(s).`);
    }
  }

  const compiled = output.contracts?.[CONTRACT_FILENAME]?.[CONTRACT_NAME];
  if (!compiled) {
    throw new Error(`Compiled artifact for ${CONTRACT_NAME} missing from solc output.`);
  }

  const artifact = {
    contractName: CONTRACT_NAME,
    sourceName: `contracts/${CONTRACT_FILENAME}`,
    compiler: {
      version: solc.version(),
      evmVersion: 'paris',
      optimizer: { enabled: true, runs: 200 },
    },
    abi: compiled.abi,
    bytecode: `0x${compiled.evm.bytecode.object}`,
    deployedBytecode: `0x${compiled.evm.deployedBytecode.object}`,
  };

  const artifactsDir = path.join(process.cwd(), 'artifacts');
  fs.mkdirSync(artifactsDir, { recursive: true });
  const artifactOutPath = path.join(artifactsDir, `${CONTRACT_NAME}.json`);
  fs.writeFileSync(artifactOutPath, JSON.stringify(artifact, null, 2), 'utf8');

  // Also emit TypeScript ABI module so client & server share exact compiled ABI with zero drift
  const libDir = path.join(process.cwd(), 'src', 'lib');
  fs.mkdirSync(libDir, { recursive: true });
  const tsAbiPath = path.join(libDir, 'trustGraphAbi.ts');
  const tsContent = `// Auto-generated by scripts/compile-contracts.ts from contracts/TrustGraphRegistry.sol
// Compiler: solc ${solc.version()}

export const TRUSTGRAPH_REGISTRY_ABI = ${JSON.stringify(compiled.abi, null, 2)} as const;
`;
  fs.writeFileSync(tsAbiPath, tsContent, 'utf8');

  console.log(`[Compile] Successfully compiled ${CONTRACT_NAME} using solc ${solc.version()}`);
  console.log(`[Compile] Wrote artifact -> artifacts/${CONTRACT_NAME}.json`);
  console.log(`[Compile] Wrote typed ABI -> src/lib/trustGraphAbi.ts`);

  return artifact;
}

// Run when invoked directly via CLI
const invokedFile = process.argv[1] || '';
if (invokedFile.endsWith('compile-contracts.ts') || invokedFile.endsWith('compile-contracts.js')) {
  try {
    compileTrustGraphRegistry();
  } catch (err: any) {
    console.error(err.message || err);
    process.exit(1);
  }
}
